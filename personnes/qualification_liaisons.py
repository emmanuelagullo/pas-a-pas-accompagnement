    def test_annuler_message_et_reponse_ne_conserve_pas_le_brouillon_abandonne(self):
        page=self.navigateur(self.social);root=self.ouvrir(page)
        root.get_by_role('button',name='Écrire un message',exact=True).click()
        root.locator('.ProseMirror').fill('Brouillon principal conservé')
        entree=root.locator('.liaisons-fil > li').filter(has_text='Message commun du dossier')
        entree.get_by_role('link',name='Répondre',exact=True).click()
        reponse=root.locator('.liaison-reponse .ProseMirror')
        reponse.fill('Réponse abandonnée ')
        reponse.press('End')
        reponse.press_sequentially('@')
        root.get_by_role('option',name='Joël Bernard',exact=True).click()
        page.once('dialog',lambda d:d.dismiss())
        root.get_by_role('link',name='Annuler',exact=True).click()
        ancien.expect(root.locator('.ProseMirror')).to_contain_text('Réponse abandonnée')
        page.once('dialog',lambda d:d.accept())
        root.get_by_role('link',name='Annuler',exact=True).click()
        ancien.expect(root.locator('.ProseMirror')).to_contain_text('Brouillon principal conservé')
        entree.get_by_role('link',name='Répondre',exact=True).click()
        ancien.expect(root.locator('.ProseMirror')).to_have_text('')
        ancien.expect(root.locator('[name=lia_mentions]')).to_have_count(0)
        root.get_by_role('link',name='Annuler',exact=True).click()
        ancien.expect(root.locator('.ProseMirror')).to_contain_text('Brouillon principal conservé')
        page.once('dialog',lambda d:d.accept())
        root.get_by_role('link',name='Annuler',exact=True).click()
        ancien.expect(root.locator('.liaison-rediger')).not_to_have_attribute('open','')
        root.get_by_role('button',name='Écrire un message',exact=True).click()
        ancien.expect(root.locator('.ProseMirror')).to_have_text('')
        ancien.expect(root.locator('.liaisons-fil')).not_to_contain_text('Réponse abandonnée')
